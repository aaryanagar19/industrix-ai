"""Generate docs that must match the code: ER diagram (from SQLAlchemy metadata), API reference (from OpenAPI), ML results (from metrics JSON).
Run from repo root:  cd backend && python ../scripts/gen_docs.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.core.db import Base  # noqa: E402
import app.models  # noqa: E402,F401
from app.main import app  # noqa: E402

docs = ROOT / "docs"


def er():
    lines = ["# Database ER Diagram", "", "Generated from the SQLAlchemy models by `scripts/gen_docs.py` (renders on GitHub via Mermaid).", "", "```mermaid", "erDiagram"]
    for t in Base.metadata.sorted_tables:
        lines.append(f"  {t.name} {{")
        for c in t.columns:
            flags = " ".join(x for x, ok in (("PK", c.primary_key), ("FK", bool(c.foreign_keys)), ("UK", bool(c.unique))) if ok)
            lines.append(f"    {str(c.type).split('(')[0].replace(' ', '_')} {c.name} {flags}".rstrip())
        lines.append("  }")
    for t in Base.metadata.sorted_tables:
        for c in t.columns:
            for fk in c.foreign_keys:
                lines.append(f"  {fk.column.table.name} ||--o{{ {t.name} : \"{c.name}\"")
    lines += ["```", "", "## Tables and indexes", ""]
    for t in Base.metadata.sorted_tables:
        idx = ", ".join(sorted(i.name for i in t.indexes)) or "-"
        lines.append(f"- **{t.name}** ({len(t.columns)} columns) - indexes: {idx}")
    (docs / "ER_DIAGRAM.md").write_text("\n".join(lines) + "\n")


def api():
    spec = app.openapi()
    lines = ["# API Reference", "", "Interactive Swagger UI: `http://localhost:8000/docs` - OpenAPI JSON: `/openapi.json`. Generated by `scripts/gen_docs.py`.", "",
             "All endpoints except `/api/auth/login`, `/api/auth/register` and `/api/health` require `Authorization: Bearer <JWT>`. WebSocket: `/ws/live?token=<JWT>`.", "", "| Method | Path | Summary |", "|---|---|---|"]
    for path, ops in sorted(spec["paths"].items()):
        for m, op in ops.items():
            lines.append(f"| {m.upper()} | `{path}` | {op.get('summary', '')} |")
    (docs / "API.md").write_text("\n".join(lines) + "\n")


def ml():
    m = ROOT / "models"
    r, a, f, n = (json.loads((m / f"metrics_{k}.json").read_text()) for k in ("risk", "anomaly", "forecast", "nlp"))
    L = ["# ML Results (auto-generated from `models/metrics_*.json`)", "", "> **All results are on SYNTHETIC data** produced by `backend/app/ml/training/data_gen.py`. They demonstrate that the pipeline works and is leakage-free; "
         "they are **not** evidence of real-world accident-prediction performance.", "", "## Accident-risk classifiers", "",
         f"- Version: `{r['version']}` - trained {r['trained_at']}", f"- Split: {r['split']}", f"- Rows train/val/test: {r['rows']['train']:,} / {r['rows']['validation']:,} / {r['rows']['test']:,}",
         f"- Positive rate train/val/test: {r['positive_rate']['train']:.2%} / {r['positive_rate']['validation']:.2%} / {r['positive_rate']['test']:.2%}", f"- Learned thresholds (calibrated probability): {r['thresholds']}", ""]
    for name, x in r["models"].items():
        L += [f"### {name}", "", f"ROC-AUC **{x['roc_auc']}** - PR-AUC **{x['pr_auc']}** - Brier (uncalibrated -> Platt-calibrated) {x['brier_uncalibrated']} -> {x['brier_calibrated']}", "",
              "| Level | Threshold | Accuracy | Precision | Recall | F1 | False-negative rate | TP | FP | FN | TN |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for lvl, v in x["at_thresholds"].items():
            c = v["confusion_matrix"]
            L.append(f"| {lvl} | {v['threshold']} | {v['accuracy']} | {v['precision']} | {v['recall']} | {v['f1']} | {v['false_negative_rate']} | {c['tp']} | {c['fp']} | {c['fn']} | {c['tn']} |")
        L.append("")
    L += ["### SHAP global importance (mean |SHAP|, log-odds)", "", "| Feature | Mean abs SHAP |", "|---|---|"] + [f"| {s['feature']} | {s['mean_abs_shap']} |" for s in r["shap_global"]]
    L += ["", "## Anomaly detector (Isolation Forest + z-score guard rail)", "", f"- Version `{a['version']}`; trained on: {a.get('training_set')}",
          f"- Flag rate on healthy held-out periods (false-alarm rate): **{a['flag_rate_healthy_periods_heldout']:.2%}**", f"- Flag rate during severe degradation: **{a['flag_rate_during_severe_degradation_heldout']:.2%}**", "- Detection of injected deviations:", ""]
    L += [f"  - {k}: {v:.1%}" for k, v in a["detection_rate_on_injected_anomalies"].items()]
    L += ["", f"> {a['note']}", "", "## LSTM forecaster", "", f"- Version `{f['version']}`; window {f['window']} h -> horizon {f['horizon']} h; samples {f['samples']}; epochs run {f['epochs_run']}", "- Test MAE in sigma units (lower is better):", "",
          "| Model | " + " | ".join(f["channels"]) + " |", "|---|" + "---|" * len(f["channels"])]
    for k, v in f["test_metrics"].items():
        L.append(f"| {k} | " + " | ".join(str(v["mae"][c]) for c in f["channels"]) + " |")
    L += ["", f"> {f['note']}", "", "## NLP classifier", "", f"- `{n['version']}`; classes {n['classes']}"] + [f"- {k}: {v}" for k, v in n.items() if "accuracy" in k] + ["", f"> {n['note']}"]
    (docs / "ML_RESULTS.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    docs.mkdir(exist_ok=True)
    er(); api(); ml()
    print("docs generated")
